    private const string Secret = "Hunter2-Secret-Value!";

    /// <summary>
    /// Set <c>EARM_UPDATE_GOLDENS=1</c> (tools/Update-WhatIfGoldens.ps1 does) to rewrite the golden files from the current output instead of
    /// comparing; review the resulting diff before committing it. Without the variable the tests only compare.
    /// </summary>
    public const string UpdateVariable = "EARM_UPDATE_GOLDENS";

    /// <summary>
    /// Whether the golden files are rewritten. A rewrite on a CI run (<c>CI=true</c>) would make every comparison trivially pass, so the update variable being
    /// set there is an error, not a request: the run fails instead of silently regenerating the expectations.
    /// </summary>
    public static bool IsUpdateRequested(string? updateValue, string? ci)
    {
        if (!string.IsNullOrEmpty(updateValue) && string.Equals(ci, "true", StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidOperationException(UpdateVariable + " is set on a CI run (CI=true): golden files must never be regenerated by CI. Unset it (the workflow sets it to empty) and regenerate locally with tools/Update-WhatIfGoldens.ps1.");
        }

        return updateValue == "1";
    }

    private static bool UpdateRequested => IsUpdateRequested(Environment.GetEnvironmentVariable(UpdateVariable), Environment.GetEnvironmentVariable("CI"));

    [Fact]
    public void CiRun_MustNotRequestAGoldenUpdate()
    {
        // Fails the whole job when a workflow (or a leaked environment) sets EARM_UPDATE_GOLDENS on a CI machine; passes everywhere else.
        _ = IsUpdateRequested(Environment.GetEnvironmentVariable(UpdateVariable), Environment.GetEnvironmentVariable("CI"));
    }

    [Theory]
    [InlineData("1", "true")]
    [InlineData("1", "True")]
    [InlineData("0", "true")]
    [InlineData("yes", "TRUE")]
    public void UpdateVariable_OnACiRun_Throws(string value, string ci)
    {
        Assert.Throws<InvalidOperationException>(() => IsUpdateRequested(value, ci));
    }

    [Theory]
    [InlineData(null, "true", false)]
    [InlineData("", "true", false)]
    [InlineData("1", null, true)]
    [InlineData("1", "false", true)]
    [InlineData("1", "", true)]
    [InlineData("0", null, false)]
    [InlineData(null, null, false)]
    public void UpdateVariable_OutsideCi_IsOnlyOnForTheValueOne(string? value, string? ci, bool expected)
    {
        Assert.Equal(expected, IsUpdateRequested(value, ci));
    }

    private static void WriteGolden(string path, string lfContent)
    {
        File.WriteAllText(path, lfContent, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    }

    public static TheoryData<string> Scenarios()
    {
        var data = new TheoryData<string>();
        foreach (var scenario in WhatIfScenario.All())
        {
            data.Add(scenario.Name);
        }

        return data;
    }

    /// <summary>Compares two renderings line by line so a failure names the first differing line instead of dumping both files.</summary>
    private static void AssertSameLines(string expected, string actual, string what)
    {
        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        for (int i = 0; i < Math.Min(expectedLines.Length, actualLines.Length); i++)
        {
            if (!string.Equals(expectedLines[i], actualLines[i], StringComparison.Ordinal))
            {
                Assert.Fail($"{what}: line {i + 1} differs.\n  expected: {expectedLines[i]}\n  actual:   {actualLines[i]}");
            }
        }

        Assert.True(expectedLines.Length == actualLines.Length, $"{what}: expected {expectedLines.Length} lines, got {actualLines.Length}.");
    }

