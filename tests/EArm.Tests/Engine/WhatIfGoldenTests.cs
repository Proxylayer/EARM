        {
            WriteGolden(run.Scenario.PathOf(run.Scenario.ExpectedJson), run.RenderJson());
            return;
        }

        AssertSameLines(run.Scenario.ReadExpectedJson(), run.RenderJson(), name + ".expected.json");
    }

